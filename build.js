#!/usr/bin/env node
// Builds the plugin and the standalone graph page from src/.
//   node build.js [--rules <file>] [--out <dir>]                 plugin: <out>/main.js, styles.css, manifest.json, rules.js (default out: dist)
//   node build.js page --data <graph.json> [--rules <file>] [--out <file>]   the graph page (default out: .out/Vault Graph.html)
// --rules is a vault's rules file (folder names, thresholds); default config/rules.json, the sample vault's.
// The renderer is one closure (mountVaultGraph) written in parts, src/view/*.js in name order: the build joins them,
// so each part can be read and reviewed on its own while they share one scope. Each scene (src/scenes/*.js) gets its
// own scope inside the renderer, so it sees the renderer's helpers but its own names can't clash with them or each other.
const fs = require("fs"), path = require("path");
const ROOT = __dirname, SRC = path.join(ROOT, "src");
const read = f => fs.readFileSync(path.join(SRC, f), "utf8");
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));

const loadRules = file => JSON.parse(fs.readFileSync(file || path.join(ROOT, "config", "rules.json"), "utf8"));

// The shared rulebook with its rule data filled in: the one place that's done (the build and every test use it).
// A function replacer, so a "$&" or "$'" in a rule pattern goes in as written.
const rulesSource = rules => read("rules.js").replace("__RULES_JSON__", () => JSON.stringify(rules));
// the rulebook, then the shared note actions (they use the rules)
const rulesJs = rules => rulesSource(rules) + "\n" + read("actions.js");

// [[name, text]] for each part of the renderer, in the order they join (tests check them one by one)
const viewParts = () => fs.readdirSync(path.join(SRC, "view")).filter(f => f.endsWith(".js")).sort()
  .map(f => [`view/${f}`, fs.readFileSync(path.join(SRC, "view", f), "utf8")]);
const viewSource = () => viewParts().map(([, t]) => t).join("");   // the renderer as one file, scenes not spliced in
function viewJs() {
  const scenes = fs.readdirSync(path.join(SRC, "scenes")).filter(f => f.endsWith(".js")).sort()
    .map(f => `\n  // ---- scene: ${f}\n  (() => {\n` + fs.readFileSync(path.join(SRC, "scenes", f), "utf8") + "\n  })();\n").join("");
  const view = viewSource();
  if (view.split("/*@scenes*/").length !== 2) throw new Error("src/view/ needs one /*@scenes*/ marker");
  return view.replace("/*@scenes*/", () => scenes);
}

// The plugin's id is the folder its content log lives in (files.content_log in the rules): "jk-vault-graph", not
// "vault-graph", which a published plugin uses (Obsidian replaced this one with it on synced devices).
const pluginId = rules => rules.files.content_log.split("/").slice(-2, -1)[0];

function buildPlugin(rules) {
  const header = "/* Vault Graph - GENERATED by build.js; do not edit.\n"
    + "   Sources: src/rules.js (+ the vault's rules file), src/actions.js, src/view/*.js (+ src/scenes/*.js), src/plugin.js. */\n";
  return {
    "main.js": header + rulesJs(rules) + "\n" + viewJs() + "\n" + read("plugin.js"),
    "styles.css": read("view.css") + "\n.vg-host { padding: 0 !important; overflow: hidden; }\n.vg-host > div { height: 100%; }\n"
      + "/* Obsidian desktop's floating status bar covers the bottom of the pane: lift the bottom chrome */\n"
      + "body:not(.is-mobile) .vg-host .vg-root { --vg-bottom: calc(var(--status-bar-height, 22px) + 8px); }\n",
    "manifest.json": JSON.stringify({
      id: pluginId(rules), name: "Vault Graph", version: pkg.version, minAppVersion: "1.4.0",
      description: "Maps the vault: topic clusters, bridge notes and gaps, with views and lenses for acting on them.",
      author: "Jackson", isDesktopOnly: false,
    }, null, 2) + "\n",
    // the rulebook on its own, for checks that compare it with the vault's Python (the vault's own tests)
    "rules.js": "/* Vault Graph rules - GENERATED by build.js; do not edit. */\n" + rulesSource(rules)
      + "\nif (typeof module !== \"undefined\") module.exports = VGRules;\n",
  };
}

const PAGE = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Vault Graph</title>
<style>
/* Obsidian's theme variables, so the shared stylesheet works outside Obsidian too */
:root { color-scheme: light dark;
        --background-primary:#ffffff; --background-secondary:#f7f7f8; --text-normal:#1d1d20; --text-muted:#6b6b76; --text-faint:#9a9aa3;
        --background-modifier-border:#e4e4e8; --background-modifier-hover:rgba(30,30,40,.06); --text-accent:#6d4aff;
        --interactive-accent:#6d4aff; --text-on-accent:#ffffff; }
@media (prefers-color-scheme: dark) { :root {
        --background-primary:#16161a; --background-secondary:#1d1d22; --text-normal:#ececf1; --text-muted:#9d9daa; --text-faint:#6e6e7a;
        --background-modifier-border:#2c2c33; --background-modifier-hover:rgba(255,255,255,.06); --text-accent:#9b87ff;
        --interactive-accent:#7c66ff; --text-on-accent:#ffffff; } }
html, body { margin:0; height:100%; background:var(--background-primary); }
__CSS__
</style></head><body>
<div id="vg" style="height:100%"></div>
<script>
__VIEW__
const DATA = __DATA__;
window.vaultGraph = mountVaultGraph(document.getElementById("vg"), DATA, {
  openNote: path => { location.href = \`obsidian://open?vault=\${encodeURIComponent(DATA.vault)}&file=\${encodeURIComponent(path.replace(/\\.md$/, ""))}\`; },
  store: {
    load: () => { try { return JSON.parse(localStorage.getItem("vault-graph:" + DATA.vault)); } catch (e) { return null; } },
    save: v => { try { localStorage.setItem("vault-graph:" + DATA.vault, JSON.stringify(v)); } catch (e) { /* private window */ } },
  },
});
</script></body></html>
`;

// The standalone page: the renderer with a vault's graph data built in, for the browser tests and for viewing outside Obsidian.
function buildPage(data, rules) {
  const js = rulesJs(rules) + "\n" + viewJs();
  // an inline <script> ends at the first "</script"; no source may contain one
  if (js.toLowerCase().includes("</script")) throw new Error("inline script contains </script");
  return PAGE.replace("__CSS__", () => read("view.css")).replace("__VIEW__", () => js)
    .replace("__DATA__", () => JSON.stringify(data).replace(/<\//g, "<\\/"));
}

// Write unless the file already holds it: an unchanged file in a synced vault isn't uploaded again.
function writeIfChanged(file, text) {
  try { if (fs.readFileSync(file, "utf8") === text) return false; } catch (e) { /* new file */ }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return true;
}

const arg = (name, dflt) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : dflt; };

if (require.main === module) {
  const rules = loadRules(arg("--rules"));
  if (process.argv[2] === "page") {
    const data = arg("--data"); if (!data) { console.error("page needs --data <graph.json>"); process.exit(2); }
    const out = arg("--out", path.join(ROOT, ".out", "Vault Graph.html"));
    writeIfChanged(out, buildPage(JSON.parse(fs.readFileSync(data, "utf8")), rules));
    console.log(`Wrote ${path.relative(process.cwd(), out)}`);
  } else {
    const out = arg("--out", path.join(ROOT, "dist"));
    for (const [f, text] of Object.entries(buildPlugin(rules))) writeIfChanged(path.join(out, f), text);
    console.log(`Built ${path.relative(process.cwd(), out) || "."}/ (${pluginId(rules)} ${pkg.version})`);
  }
}

module.exports = { ROOT, loadRules, rulesSource, viewParts, viewSource, buildPlugin, buildPage, pluginId, writeIfChanged };
