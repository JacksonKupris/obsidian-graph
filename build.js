// The standalone page: the renderer with a vault's graph data built in, for the browser tests and for viewing outside Obsidian.
function buildPage(data, rules) {
  const js = rulesJs(rules) + "\n" + viewJs();
  // an inline <script> ends at the first "</script"; no source may contain one
  if (js.toLowerCase().includes("</script")) throw new Error("inline script contains </script");
  return PAGE.replace("__CSS__", () => read("tokens.css") + read("parts.css") + read("view.css")).replace("__VIEW__", () => js)
    .replace("__DATA__", () => JSON.stringify(data).replace(/<\//g, "<\\/"));
}

// The HQ page: Vault HQ (src/hq.js) with a vault's graph data and its HQ notes built in, for the browser tests. A test
// puts its own mount options (stand-ins for the plugin's actions, a fixed clock) at HQ_OPTS; they win over the page's.
const HQ_OPTS = "/*@hq-opts*/";
function buildHQPage(data, rules) {
  const js = rulesJs(rules) + "\n" + hqJs();
  if (js.toLowerCase().includes("</script")) throw new Error("inline script contains </script");
  // Obsidian's own rules for every button (mobile's included): HQ is tested against them, since they win over a
  // single class (a project card showed one clipped line on the phone)
  const obsidianButtons = "button { display: inline-flex; align-items: center; justify-content: center; white-space: nowrap; overflow: hidden; height: 30px; padding: 4px 12px; background-color: #3a3a3a; box-shadow: 0 1px 2px rgba(0,0,0,.4); text-align: center; }\n";
  return PAGE.split("<script>")[0].replace("<title>Vault Graph</title>", "<title>Vault HQ</title>").replace("__CSS__", () => obsidianButtons + read("tokens.css") + read("parts.css") + read("hq.css"))
    .replace('<div id="vg" style="height:100%"></div>', '<div id="hq" style="height:100%"></div>')
    + `<script>\n${js}\nconst DATA = ${JSON.stringify(data).replace(/<\//g, "<\\/")};\n`
    + `window.vaultHQ = mountVaultHQ(document.getElementById("hq"), DATA, {\n  api: { openNote: p => { (window.__opened = window.__opened || []).push(p); } },\n  ${HQ_OPTS}\n});\n</script></body></html>\n`;
}

// Write unless the file already holds it: an unchanged file in a synced vault isn't uploaded again.
function writeIfChanged(file, text) {
  try { if (fs.readFileSync(file, "utf8") === text) return false; } catch (e) { /* new file */ }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return true;
}

const arg = (name, dflt) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : dflt; };

if (require.main === module) {
  const rules = loadRules(arg("--rules"));
  if (process.argv[2] === "manifest") {   // the repo's own manifest.json, which BRAT and Obsidian read for the version
    writeIfChanged(path.join(ROOT, "manifest.json"), buildPlugin(rules)["manifest.json"]);
    console.log(`Wrote manifest.json (${pluginId(rules)} ${pkg.version})`);
  } else if (process.argv[2] === "page") {
    const data = arg("--data"); if (!data) { console.error("page needs --data <graph.json>"); process.exit(2); }
    const out = arg("--out", path.join(ROOT, ".out", "Vault Graph.html"));
    writeIfChanged(out, buildPage(JSON.parse(fs.readFileSync(data, "utf8")), rules));
    console.log(`Wrote ${path.relative(process.cwd(), out)}`);
  } else {
    const out = arg("--out", path.join(ROOT, "dist"));
    for (const [f, text] of Object.entries(buildPlugin(rules))) writeIfChanged(path.join(out, f), text);
    console.log(`Built ${path.relative(process.cwd(), out) || "."}/ (${pluginId(rules)} ${pkg.version})`);
  }
}

module.exports = { ROOT, loadRules, pluginSource, rulesSource, engineSource, scienceSource, actionsSource, viewParts, viewSource, buildPlugin, buildPage, buildHQPage, HQ_OPTS, pluginId, writeIfChanged };
